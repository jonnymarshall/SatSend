/**
 * Draws the payment-state icons for emails (v1.5.28, roadmap v1.5.2.21-H):
 * the same Lucide icon in the same soft circle as the client's invoice page,
 * as a PNG, because email apps strip SVG.
 *
 *   npx tsx scripts/email/build-status-icons.tsx
 *
 * Writes public/brand/email-status-<state>.png and the inline copies in
 * src/lib/email/status-icons-inline.ts (the public folder is not part of the
 * server bundle on Vercel). A test fails if the two differ.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { CircleCheck, CirclePlus, Clock, TriangleAlert, type LucideIcon } from "lucide-react";
import sharp from "sharp";
import { statusColors } from "../../src/lib/brand-colors";

const STATES: Record<string, { Icon: LucideIcon; colors: { fill: string; text: string } }> = {
  payment_detected: { Icon: Clock, colors: statusColors.payment_detected },
  paid: { Icon: CircleCheck, colors: statusColors.paid },
  underpaid: { Icon: TriangleAlert, colors: statusColors.underpaid },
  overpaid: { Icon: CirclePlus, colors: statusColors.overpaid },
};

// Shown at 64px, drawn at 3x so it stays sharp on high-density screens.
const DISPLAY = 64;
const SCALE = 3;

async function main() {
  const root = path.resolve(__dirname, "../..");
  const lines: string[] = [];

  for (const [state, { Icon, colors }] of Object.entries(STATES)) {
    const icon = renderToStaticMarkup(createElement(Icon, { size: 32, color: colors.text, strokeWidth: 2 }))
      .replace("<svg ", '<svg x="16" y="16" ');
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${DISPLAY}" height="${DISPLAY}" viewBox="0 0 64 64"><circle cx="32" cy="32" r="32" fill="${colors.fill}"/>${icon}</svg>`;
    const png = await sharp(Buffer.from(svg), { density: 72 * SCALE }).png().toBuffer();
    const file = `public/brand/email-status-${state}.png`;
    writeFileSync(path.join(root, file), png);
    lines.push(`  ${state}: "${png.toString("base64")}",`);
    console.log(`wrote ${file}`);
  }

  writeFileSync(
    path.join(root, "src/lib/email/status-icons-inline.ts"),
    `// Generated by scripts/email/build-status-icons.tsx. Do not edit by hand.
// The payment-state icons for emails (v1.5.28), sent inside each email as an
// inline attachment like the logo (v1.5.12). Copies of
// public/brand/email-status-<state>.png; a test fails if they differ.
import type { PaymentState } from "@/lib/invoices/payment-summary";

const PNG_BASE64: Record<PaymentState, string> = {
${lines.join("\n")}
};

export function statusIconContentId(state: PaymentState): string {
  return \`satsend-status-\${state.replace("_", "-")}\`;
}

export function statusIconAttachment(state: PaymentState) {
  return {
    filename: \`\${statusIconContentId(state)}.png\`,
    content: PNG_BASE64[state],
    contentType: "image/png",
    contentId: statusIconContentId(state),
  };
}
`,
  );
  console.log("wrote src/lib/email/status-icons-inline.ts");
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
